export type Strings = typeof EN;

export function translate(lang: Language, key: StringKey, vars: Record<string, string | number> = {}): string {
  const raw = (lang === "es" ? ES : EN)[key];
  return raw.replace(/\{(\w+)\}/g, (_, name: string) => (name in vars ? String(vars[name]) : `{${name}}`));
}

export function translateNow(key: StringKey, vars: Record<string, string | number> = {}): string {
  return translate(currentLanguage(), key, vars);
}

export function countedNow(n: number, one: StringKey, many: StringKey): string {
  const lang = currentLanguage();
  return `${n} ${new Intl.PluralRules(lang).select(n) === "one" ? translate(lang, one) : translate(lang, many)}`;
}

export type Stringer = {
  lang: Language;
  t: (key: StringKey, vars?: Record<string, string | number>) => string;
  counted: (n: number, one: StringKey, many: StringKey) => string;
};

export function useStrings(): Stringer {
  const lang = useLanguage();
  return {
    lang,
    t: (key, vars) => translate(lang, key, vars),
    counted: (n, one, many) => `${n} ${new Intl.PluralRules(lang).select(n) === "one" ? translate(lang, one) : translate(lang, many)}`,
  };
}
